CREATE TABLE calculos_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piso_nome VARCHAR(200) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    resultado JSONB NOT NULL,
    parametros JSONB NOT NULL
);
CREATE INDEX idx_calculos_historico_recent ON calculos_historico (criado_em DESC, id DESC);
CREATE TABLE status_cores (
    codigo VARCHAR(40) PRIMARY KEY,
    cor VARCHAR(7) NOT NULL CHECK (cor ~ '^#[0-9A-Fa-f]{6}$'),
    versao BIGINT NOT NULL DEFAULT 0
);
